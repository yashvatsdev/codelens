class PRCommenterError(Exception):
    """Base exception for PR commenter errors."""
    pass


class GitHubCredentialsUnavailableError(PRCommenterError):
    """Raised when GitHub token/credentials are missing or unauthorized."""
    pass


# ---------------------------------------------------------------------------
# Markdown comment builder
# ---------------------------------------------------------------------------

def format_pr_review_comment(
    summary: str,
    risk_level: str,
    overall_assessment: str,
    key_findings: list[dict],
    recommendations: list[str],
    include_findings: bool = True,
) -> str:
    """Construct a clean, professional GitHub Markdown comment from PR review data.

    Contains:
    - CodeLens header
    - Risk level
    - Overall assessment
    - Key findings (with severity, category, file path, line number, issue, impact, recommendation)
    - Prioritized recommendations
    """
    normalized_risk = risk_level.strip().lower()
    risk_emoji = {
        "critical": "🔴",
        "high": "🟠",
        "medium": "🟡",
        "low": "🟢",
    }.get(normalized_risk, "⚪")

    lines: list[str] = [
        "## 🔍 CodeLens AI PR Review",
        "",
        f"**Risk Level:** {risk_emoji} `{normalized_risk.upper()}`",
    ]

    if summary and summary.strip():
        lines.extend([
            "",
            f"> {summary.strip()}",
        ])

    if overall_assessment and overall_assessment.strip():
        lines.extend([
            "",
            "### 📋 Overall Assessment",
            overall_assessment.strip(),
        ])

    if include_findings:
        lines.extend([
            "",
            f"### 🚨 Key Findings ({len(key_findings)})",
        ])
        if not key_findings:
            lines.extend([
                "",
                "> ✅ **No critical issues detected.** CodeLens static analysis and AI review found no security, bug, or style defects in the changed lines of this PR.",
            ])
        else:
            for i, finding in enumerate(key_findings, 1):
                severity = str(finding.get("severity", "info")).upper()
                category = str(finding.get("category", "general")).capitalize()
                file_path = finding.get("file_path", "unknown")
                line_num = finding.get("line_number")
                loc = f"`{file_path}:{line_num}`" if line_num is not None else f"`{file_path}`"
                issue = finding.get("issue", "Issue detected.")
                impact = finding.get("impact", "")
                rec = finding.get("recommendation", "")

                lines.extend([
                    "",
                    f"#### {i}. [{severity}] {loc} — {category}",
                    f"- **Issue:** {issue}",
                ])
                if impact:
                    lines.append(f"- **Impact:** {impact}")
                if rec:
                    lines.append(f"- **Recommendation:** {rec}")

    if recommendations:
        lines.extend([
            "",
            "### 💡 Prioritized Recommendations",
        ])
        for i, rec in enumerate(recommendations, 1):
            lines.append(f"{i}. {rec}")

    lines.extend([
        "",
        "---",
        "*Review automatically generated by [CodeLens](https://github.com/yashvatsdev/codelens) — Diff-aware AI Code Review*",
    ])

    return "\n".join(lines)


# ---------------------------------------------------------------------------
# GitHub REST API client for posting comments
# ---------------------------------------------------------------------------

def post_github_pr_comment(
    owner: str,
    repo: str,
    pr_number: int,
    body: str,
    token: str | None = None,
    timeout: int = 15,
) -> dict:
    """Post an issue/PR comment to GitHub using authenticated credentials.

    Endpoint: POST https://api.github.com/repos/{owner}/{repo}/issues/{pr_number}/comments

    Args:
        owner: Repository owner/organization.
        repo: Repository name.
        pr_number: Pull request number.
        body: Markdown content of the comment.
        token: Optional GitHub token override; defaults to settings.github_token.
        timeout: Request timeout in seconds.

    Returns:
        dict: Parsed GitHub API response containing `id`, `html_url`, etc.

    Raises:
        GitHubCredentialsUnavailableError: If token is missing or invalid.
        PRNotFoundError: If PR or repository is not found.
        GitHubRateLimitError: If rate limit is hit.
        GitHubAPIError: For other network or API errors.
    """
    auth_token = token or settings.github_token
    if not auth_token:
        raise GitHubCredentialsUnavailableError(
            "GitHub credentials are unavailable (missing GITHUB_TOKEN)"
        )

    url = f"https://api.github.com/repos/{owner}/{repo}/issues/{pr_number}/comments"
    payload = json.dumps({"body": body}).encode("utf-8")

    req = urllib.request.Request(
        url,
        data=payload,
        headers={
            "User-Agent": "CodeLens-App",
            "Accept": "application/vnd.github+json",
            "Content-Type": "application/json",
            "Authorization": f"Bearer {auth_token}",
        },
        method="POST",
    )

    try:
        with urllib.request.urlopen(req, timeout=timeout) as response:
            return json.loads(response.read().decode("utf-8"))
    except urllib.error.HTTPError as err:
        if err.code == 404:
            raise PRNotFoundError(
                f"Pull request #{pr_number} not found: {url}"
            ) from err
        if err.code == 401:
            raise GitHubCredentialsUnavailableError(
                "GitHub authentication failed (invalid or expired GITHUB_TOKEN)"
            ) from err
        if err.code == 403:
            rate_remaining = err.headers.get("x-ratelimit-remaining")
            if rate_remaining == "0" or "rate limit" in str(err.reason).lower():
                raise GitHubRateLimitError(
                    "GitHub API rate limit exceeded. Please try again later."
                ) from err
            raise GitHubCredentialsUnavailableError(
                f"GitHub permission denied: {err.reason}"
            ) from err
        raise GitHubAPIError(
            f"GitHub API returned error {err.code}: {err.reason}"
        ) from err
    except urllib.error.URLError as err:
        raise GitHubAPIError(
            f"Failed to reach GitHub API: {err.reason}"
        ) from err
    except TimeoutError as err:
        raise GitHubAPIError(
            "Request to GitHub API timed out."
        ) from err


