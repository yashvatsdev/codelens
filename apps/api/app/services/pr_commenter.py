def create_pr_review_comment(
    repository: Repository,
    pull_request_number: int,
    summary: str | None = None,
    include_findings: bool = True,
    token: str | None = None,
    gemini_client: Any = None,
) -> dict:
    """Run diff-aware review, generate review summary, and post comment to GitHub PR.

    Args:
        repository: Repository model instance.
        pull_request_number: Pull request number.
        summary: Optional custom review summary.
        include_findings: Whether to include individual key findings.
        token: Optional GitHub token override.
        gemini_client: Optional mock Gemini client.

    Returns:
        dict with repository_id, pull_request_number, comment_id, comment_url, risk_level, findings_posted.
    """
    auth_token = token or settings.github_token
    if not auth_token:
        raise GitHubCredentialsUnavailableError(
            "GitHub credentials are unavailable (missing GITHUB_TOKEN)"
        )

    # 1. Run diff-aware PR review pipeline
    review_result = review_pull_request(
        owner=repository.owner,
        repo=repository.name,
        pr_number=pull_request_number,
        repository_id=repository.id,
    )

    # 2. Run AI PR review if Gemini is configured or mock client provided
    ai_review_succeeded = False
    if settings.gemini_api_key or gemini_client is not None:
        try:
            ai_review = generate_ai_pr_review(
                review_result=review_result,
                repo_full_name=repository.full_name,
                gemini_client=gemini_client,
            )
            risk_level = str(ai_review.get("risk_level", "low")).lower()
            review_summary = summary or ai_review.get("summary", "Code review completed.")
            overall_assessment = ai_review.get("overall_assessment", "")
            key_findings = ai_review.get("key_findings", [])
            recommendations = ai_review.get("recommendations", [])
            ai_review_succeeded = True
        except Exception as exc:
            logger.warning(
                "Gemini AI PR review generation failed, falling back to static analysis findings: %s",
                exc,
            )

    if not ai_review_succeeded:
        # Fallback review from static analysis findings
        findings_count = len(review_result.findings)
        has_errors = any(f.severity.lower() in ("error", "critical") for f in review_result.findings)
        risk_level = "low" if findings_count == 0 else ("high" if has_errors else "medium")
        if findings_count == 0:
            default_summary = f"CodeLens analyzed {review_result.files_analyzed} files in PR #{pull_request_number} with no issues detected."
        else:
            default_summary = f"CodeLens analyzed {review_result.files_analyzed} files in PR #{pull_request_number} and found {findings_count} potential issues."
        review_summary = summary or default_summary
        overall_assessment = "Diff-aware static code analysis completed for pull request changed lines."
        key_findings = [
            {
                "file_path": f.file_path,
                "line_number": f.line_number,
                "severity": f.severity,
                "category": f.category,
                "issue": f.message,
                "impact": f"Triggers static rule {f.rule_id}.",
                "recommendation": f"Remediate {f.rule_id} in {f.file_path}:{f.line_number or 1}.",
            }
            for f in review_result.findings
        ]
        recommendations = [
            "Review and resolve static analysis findings before merging."
        ] if findings_count > 0 else [
            "Code changes look clean and adhere to project standards."
        ]

    # 3. Format markdown comment
    comment_body = format_pr_review_comment(
        summary=review_summary,
        risk_level=risk_level,
        overall_assessment=overall_assessment,
        key_findings=key_findings,
        recommendations=recommendations,
        include_findings=include_findings,
    )

    # 4. Post comment to GitHub PR
    comment_data = post_github_pr_comment(
        owner=repository.owner,
        repo=repository.name,
        pr_number=pull_request_number,
        body=comment_body,
        token=auth_token,
    )

    findings_posted = len(key_findings) if include_findings else 0

    return {
        "repository_id": repository.id,
        "pull_request_number": pull_request_number,
        "comment_id": comment_data.get("id"),
        "comment_url": comment_data.get("html_url"),
        "risk_level": risk_level,
        "findings_posted": findings_posted,
    }
